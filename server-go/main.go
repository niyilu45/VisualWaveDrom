func (s *service) handleLibraries(writer http.ResponseWriter, _ *http.Request) {
	libraries := s.listLibraries()
	currentName := ""
	recent := s.readRecentLibraryName()
	for _, library := range libraries {
		if library.Name == recent {
			currentName = library.Name
			break
		}
	}
	if currentName == "" {
		for _, library := range libraries {
			if library.Name == s.config.configuredName {
				currentName = library.Name
				break
			}
		}
	}
	if currentName == "" && len(libraries) > 0 {
		currentName = libraries[0].Name
	}
	currentID := ""
	for _, library := range libraries {
		if library.Name == currentName {
			currentID = library.LibraryID
		}
	}
	files := make([]string, len(libraries))
	for index, library := range libraries {
		files[index] = library.Name
	}
	sendJSON(writer, 200, map[string]any{
		"files": files, "libraries": libraries, "current": currentName,
		"currentLibraryId": currentID, "protocolScheme": s.activeScheme,
	})
}

func normalizeLibraryIdentity(library *waveLibrary) {
	if library.LibraryID == "" {
		library.LibraryID = stableID("library")
	}
	if library.Version < 2 {
		library.Version = 2
	}
	for _, document := range library.Documents {
		revision := intValue(document["revision"], 0)
		if revision < 0 {
			revision = 0
		}
		document["revision"] = revision
	}
}

func documentsByName(documents []map[string]any) map[string]map[string]any {
	result := make(map[string]map[string]any)
	for _, document := range documents {
		name := stringValue(document["name"])
		if name != "" {
			result[name] = document
		}
	}
	return result
}

func (s *service) handleWaveLibrary(writer http.ResponseWriter, request *http.Request) {
	filePath := s.resolveRequestLibrary(request.URL, true)
	if filePath == "" {
		sendJSON(writer, 400, map[string]any{"error": "Invalid library"})
		return
	}
	switch request.Method {
	case http.MethodGet:
		if !s.store.isLibraryFile(filePath) {
			sendJSON(writer, 404, map[string]any{"error": "Library not found"})
			return
		}
		library, err := s.store.readLibrary(filePath, request.URL.Query().Get("summary") == "1")
		if err != nil {
			sendJSON(writer, 400, map[string]any{"error": err.Error()})
			return
		}
		s.rememberLibraryName(s.libraryNameFromPath(filePath))
		sendJSON(writer, 200, library)
	case http.MethodPost:
		var incoming waveLibrary
		if err := decodeJSONBody(writer, request, maxWaveLibraryRequestBytes, &incoming); err != nil {
			sendJSON(writer, 400, map[string]any{"error": err.Error()})
			return
		}
		if incoming.Kind != libraryKind || incoming.Documents == nil {
			sendJSON(writer, 400, map[string]any{"error": "Invalid library"})
			return
		}
		var existing *waveLibrary
		if s.store.isLibraryFile(filePath) {
			value, err := s.store.readLibrary(filePath, false)
			if err != nil {
				sendJSON(writer, 400, map[string]any{"error": err.Error()})
				return
			}
			existing = &value
		}
		if incoming.LibraryID == "" && existing != nil {
			incoming.LibraryID = existing.LibraryID
		}
		if existing != nil && incoming.LibraryID != existing.LibraryID {
			sendJSON(writer, 409, map[string]any{
				"error": "Library identity conflict", "libraryId": existing.LibraryID,
			})
			return
		}
		normalizeLibraryIdentity(&incoming)
		if existing != nil {
			existingDocuments := documentsByName(existing.Documents)
			for _, document := range incoming.Documents {
				current := existingDocuments[stringValue(document["name"])]
				if current == nil || intValue(document["revision"], 0) == intValue(current["revision"], 0) {
					continue
				}
				if documentsHaveSameState(document, current) {
					document["revision"] = current["revision"]
					continue
				}
				sendJSON(writer, 409, map[string]any{
					"error": "Wave document revision conflict", "waveId": document["name"],
				})
				return
			}
		}
		incoming.UpdatedAt = isoNow()
		if err := s.store.writeLibrary(filePath, incoming); err != nil {
			sendJSON(writer, 400, map[string]any{"error": err.Error()})
			return
		}
		s.rememberLibraryName(s.libraryNameFromPath(filePath))
		sendJSON(writer, 200, map[string]any{
			"ok": true, "file": filepath.Base(filepath.Dir(filePath)),
			"libraryId": incoming.LibraryID,
		})
	default:
		writer.WriteHeader(http.StatusMethodNotAllowed)
	}
}

func (s *service) handleLibraryState(writer http.ResponseWriter, request *http.Request) {
	payload := make(map[string]any)
	if err := decodeJSONBody(writer, request, maxWaveLibraryRequestBytes, &payload); err != nil {
		sendJSON(writer, 400, map[string]any{"error": err.Error()})
		return
	}
	libraryID := stringValue(payload["libraryId"])
	filePath := s.libraryPathByID(libraryID)
	if filePath == "" {
		sendJSON(writer, 404, map[string]any{"error": "Wave library not found"})
		return
	}
	result, err := s.store.patchLibraryState(filePath, payload)
	if err != nil {
		sendJSON(writer, 400, map[string]any{"error": err.Error()})
		return
	}
	if result.Status == 409 {
		sendJSON(writer, 409, map[string]any{"error": result.Error, "waveId": result.WaveID})
		return
	}
	sendJSON(writer, 200, map[string]any{
		"ok": true, "libraryId": libraryID, "file": filepath.Base(filepath.Dir(filePath)),
		"revisions": result.Revisions, "deletedDocuments": result.DeletedDocuments,
	})
}

func (s *service) handleWaveDocument(writer http.ResponseWriter, request *http.Request) {
	switch request.Method {
	case http.MethodGet:
		filePath := s.resolveRequestLibrary(request.URL, false)
		waveID := request.URL.Query().Get("waveId")
		if filePath == "" || waveID == "" || !s.store.isLibraryFile(filePath) {
			sendJSON(writer, 404, map[string]any{"error": "Wave document not found"})
			return
		}
		library, err := s.store.readLibrary(filePath, true)
		if err != nil {
			sendJSON(writer, 400, map[string]any{"error": err.Error()})
			return
		}
		document, err := s.store.readDocument(filePath, waveID)
		if err != nil {
			sendJSON(writer, 400, map[string]any{"error": err.Error()})
			return
		}
		if document == nil {
			sendJSON(writer, 404, map[string]any{"error": "Wave document not found"})
			return
		}
		sendJSON(writer, 200, map[string]any{
			"libraryId": library.LibraryID, "file": filepath.Base(filepath.Dir(filePath)),
			"document": document,
		})
	case http.MethodPatch:
		payload := make(map[string]any)
		if err := decodeJSONBody(writer, request, maxWaveLibraryRequestBytes, &payload); err != nil {
			sendJSON(writer, 400, map[string]any{"error": err.Error()})
			return
		}
		libraryID := stringValue(payload["libraryId"])
		waveID := stringValue(payload["waveId"])
		filePath := s.libraryPathByID(libraryID)
		document, documentOK := payload["document"].(map[string]any)
		if filePath == "" || waveID == "" || !documentOK {
			sendJSON(writer, 404, map[string]any{"error": "Wave document not found"})
			return
		}
		var expectedRevision *int
		if revision, ok := integerValue(payload["expectedRevision"]); ok {
			expectedRevision = &revision
		}
		result, err := s.store.updateDocument(filePath, waveID, expectedRevision, document)
		if err != nil {
			sendJSON(writer, 400, map[string]any{"error": err.Error()})
			return
		}
		if result.Status != 200 {
			sendJSON(writer, result.Status, map[string]any{
				"error": result.Error, "document": result.Document,
			})
			return
		}
		sendJSON(writer, 200, map[string]any{
			"ok": true, "libraryId": libraryID, "file": filepath.Base(filepath.Dir(filePath)),
			"document": result.Document,
		})
	default:
		writer.WriteHeader(http.StatusMethodNotAllowed)
	}
}

func contentType(filePath string) string {
	extension := strings.ToLower(filepath.Ext(filePath))
	if extension == ".js" {
		return "application/javascript; charset=utf-8"
	}
	if extension == ".json" {
		return "application/json; charset=utf-8"
	}
	if extension == ".svg" {
		return "image/svg+xml"
	}
	if extension == ".wasm" {
		return "application/wasm"
	}
	if detected := mime.TypeByExtension(extension); detected != "" {
		return detected
	}
	return "application/octet-stream"
}

func (s *service) serveStatic(writer http.ResponseWriter, request *http.Request) {
	relative := strings.TrimLeft(request.URL.Path, "/")
	if relative == "" {
		relative = s.config.htmlName
	}
	unescaped, err := url.PathUnescape(relative)
	if err != nil {
		http.NotFound(writer, request)
		return
	}
	target, err := filepath.Abs(filepath.Join(s.config.rootDir, filepath.FromSlash(unescaped)))
	if err != nil || !pathInside(s.config.rootDir, target) {
		http.NotFound(writer, request)
		return
	}
	info, err := os.Stat(target)
	if err != nil || info.IsDir() {
		http.NotFound(writer, request)
		return
	}
	realTarget := canonicalExistingPath(target)
	if !pathInside(canonicalExistingPath(s.config.rootDir), realTarget) {
		http.NotFound(writer, request)
		return
	}
	file, err := os.Open(realTarget)
	if err != nil {
		http.NotFound(writer, request)
		return
	}
	defer file.Close()
	writer.Header().Set("Content-Type", contentType(realTarget))
	writer.Header().Set("X-Content-Type-Options", "nosniff")
	switch strings.ToLower(filepath.Ext(realTarget)) {
	case ".html", ".htm":
		writer.Header().Set("Cache-Control", "no-cache, no-store, must-revalidate")
		writer.Header().Set("Pragma", "no-cache")
		writer.Header().Set("Expires", "0")
	case ".js", ".css":
		writer.Header().Set("Cache-Control", "no-cache")
	}
	http.ServeContent(writer, request, info.Name(), info.ModTime(), file)
}

func (s *service) routes() http.Handler {
	mux := http.NewServeMux()
	mux.HandleFunc("/open", func(writer http.ResponseWriter, request *http.Request) {
		if request.Method != http.MethodGet {
			writer.WriteHeader(http.StatusMethodNotAllowed)
			return
		}
		query := request.URL.Query()
		http.Redirect(writer, request, "/"+url.PathEscape(s.config.htmlName)+"?"+query.Encode(),
			http.StatusFound)
	})
	mux.HandleFunc("/api/server-info", method(http.MethodGet, s.handleServerInfo))
	mux.HandleFunc("/api/client-connect", method(http.MethodPost, s.handleClientConnect))
	mux.HandleFunc("/api/client-disconnect", method(http.MethodPost, s.handleClientDisconnect))
	mux.HandleFunc("/api/client-session", method(http.MethodGet, s.handleClientSession))
	mux.HandleFunc("/api/import-schemes", method(http.MethodGet, s.handleImportSchemes))
	mux.HandleFunc("/api/import-wave-analyze", method(http.MethodPost, s.handleImportAnalyze))
	mux.HandleFunc("/api/import-wave-preview", method(http.MethodPost, s.handleImportPreview))
	mux.HandleFunc("/api/import-wave-row", method(http.MethodPost, s.handleImportRow))
	mux.HandleFunc("/api/import-wave-collection", method(http.MethodPost, s.handleImportCollection))
	mux.HandleFunc("/api/wave-libraries", method(http.MethodGet, s.handleLibraries))
	mux.HandleFunc("/api/wave-library", s.handleWaveLibrary)
	mux.HandleFunc("/api/wave-library-state", method(http.MethodPatch, s.handleLibraryState))
	mux.HandleFunc("/api/wave-document", s.handleWaveDocument)
	mux.HandleFunc("/", s.serveStatic)
	return mux
}

func method(expected string, handler http.HandlerFunc) http.HandlerFunc {
	return func(writer http.ResponseWriter, request *http.Request) {
		if request.Method != expected {
			writer.WriteHeader(http.StatusMethodNotAllowed)
			return
		}
		handler(writer, request)
	}
}

func normalizedPath(value string) string {
	resolved, _ := filepath.Abs(value)
	if runtime.GOOS == "windows" {
		return strings.ToLower(resolved)
	}
	return resolved
}

func probeServer(port int) map[string]any {
	client := &http.Client{Timeout: 800 * time.Millisecond}
	response, err := client.Get(fmt.Sprintf("http://127.0.0.1:%d/api/server-info", port))
	if err != nil {
		return nil
	}
	defer response.Body.Close()
	if response.StatusCode != 200 {
		return nil
	}
	reader := io.LimitReader(response.Body, 64*1024)
	var info map[string]any
	if json.NewDecoder(reader).Decode(&info) != nil {
		return nil
	}
	return info
}

func (s *service) sameRunningService(info map[string]any) bool {
	return stringValue(info["app"]) == appID &&
		intValue(info["serviceAPIVersion"], 0) == serviceAPIVersion &&
		stringValue(info["htmlName"]) == s.config.htmlName &&
		stringValue(info["currentLibrary"]) == s.config.configuredName &&
		normalizedPath(stringValue(info["rootDir"])) == normalizedPath(s.config.rootDir) &&
		normalizedPath(stringValue(info["libraryDir"])) == normalizedPath(s.config.waveDir)
}

func listenLocal(port int) (net.Listener, error) {
	return net.Listen("tcp", fmt.Sprintf("127.0.0.1:%d", port))
}

func (s *service) run() error {
	s.registerProtocolHandler()
	listener, err := listenLocal(s.config.port)
	if err != nil {
		if info := probeServer(s.config.port); s.sameRunningService(info) {
			address := s.pageAddress(s.config.port)
			fmt.Printf("VisualWaveDrom is already running at %s\n", address)
			openBrowser(address, s.config.noOpen)
			return nil
		}
		listener, err = listenLocal(0)
		if err != nil {
			return err
		}
		fmt.Printf("Port %d is already in use; using an available port.\n", s.config.port)
	}
	activePort := listener.Addr().(*net.TCPAddr).Port
	address := s.pageAddress(activePort)
	s.httpServer = &http.Server{
		Handler:           s.routes(),
		ReadHeaderTimeout: 10 * time.Second,
		IdleTimeout:       90 * time.Second,
		MaxHeaderBytes:    1 * 1024 * 1024,
	}
	fmt.Printf("Runtime: %s/%s / Go %s / SQLite %s\n",
		runtime.GOOS, runtime.GOARCH, runtime.Version(), s.sqliteVersion)
	fmt.Printf("VisualWaveDrom is running at %s\n", address)
	if !s.config.noOpen {
		s.clientMu.Lock()
		s.scheduleClientShutdownLocked(clientStartupGracePeriod)
		s.clientMu.Unlock()
	}
	openBrowser(address, s.config.noOpen)
	err = s.httpServer.Serve(listener)
	if errors.Is(err, http.ErrServerClosed) {
		return nil
	}
	return err
}

func main() {
	log.SetFlags(0)
	configuration, err := parseConfig()
	if err != nil {
		log.Fatalf("VisualWaveDrom startup failed: %v", err)
	}
	instance, err := newService(configuration)
	if err != nil {
		log.Fatalf("VisualWaveDrom startup failed: %v", err)
	}
	if configuration.checkRuntime {
		fmt.Printf("Platform:       %s %s\n", runtime.GOOS, runtime.GOARCH)
		fmt.Printf("Server:         Go %s (%s)\n", runtime.Version(), buildVersion)
		fmt.Printf("SQLite:         embedded %s\n", instance.sqliteVersion)
		fmt.Printf("HTML:           %s\n", configuration.htmlPath)
		fmt.Printf("Wave library:   %s\n", configuration.configuredLibrary)
		return
	}
	if err = instance.run(); err != nil {
		log.Fatalf("VisualWaveDrom failed to start: %v", err)
	}
}
